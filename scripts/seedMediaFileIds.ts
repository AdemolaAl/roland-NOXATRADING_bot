// One-time (and idempotent) media seeder.
//
// Uploads every image in images/ to a private Telegram chat using the same
// BOT_TOKEN the bot will send with, captures the largest returned photo's
// file_id, and writes src/bot/generated/fileIds.ts.
//
// Re-running is safe: filenames already in the generated map are skipped, so
// an interrupted or rate-limited run can be resumed by simply running again.
//
// Required env:
//   BOT_TOKEN           — the production bot token (file_ids are bot-scoped)
//   MEDIA_SEED_CHAT_ID  — private channel/group id, e.g. -1003851679476
//
// Usage:
//   npm run seed:media
//
// Flags:
//   --force  Wipe the existing map and re-upload every image.

import fs from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { Telegraf } from 'telegraf'

const BOT_TOKEN = process.env.BOT_TOKEN
const CHAT_ID = process.env.MEDIA_SEED_CHAT_ID
const FORCE = process.argv.includes('--force')

if (!BOT_TOKEN) {
  console.error('[seed] missing BOT_TOKEN')
  process.exit(1)
}
if (!CHAT_ID) {
  console.error('[seed] missing MEDIA_SEED_CHAT_ID (the private channel/group id)')
  process.exit(1)
}

const IMAGE_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp'])
const IMAGES_DIR = path.resolve(process.cwd(), 'images')
const OUTPUT_DIR = path.resolve(process.cwd(), 'src/bot/generated')
const OUTPUT_FILE = path.join(OUTPUT_DIR, 'fileIds.ts')

// Telegram returns photo sizes in ascending order, but sort by area to be
// defensive — the largest entry is the one we want to keep as the cached
// reference (smaller thumbnails would visibly downgrade send quality).
function pickLargest<T extends { width?: number; height?: number; file_size?: number; file_id: string }>(
  photos: T[],
): T | undefined {
  if (photos.length === 0) return undefined
  return [...photos].sort((a, b) => {
    const aSize = a.file_size ?? (a.width ?? 0) * (a.height ?? 0)
    const bSize = b.file_size ?? (b.width ?? 0) * (b.height ?? 0)
    return bSize - aSize
  })[0]
}

interface SeedShape {
  SEEDED_BOT_ID: string | null
  FILE_IDS: Record<string, string>
}

async function loadExisting(): Promise<SeedShape> {
  if (FORCE || !existsSync(OUTPUT_FILE)) {
    return { SEEDED_BOT_ID: null, FILE_IDS: {} }
  }
  const mod = (await import(pathToFileURL(OUTPUT_FILE).href)) as Partial<SeedShape>
  return {
    SEEDED_BOT_ID: mod.SEEDED_BOT_ID ?? null,
    FILE_IDS: { ...(mod.FILE_IDS ?? {}) },
  }
}

function serialize(shape: SeedShape): string {
  const header = [
    '// AUTO-GENERATED by scripts/seedMediaFileIds.ts — do not edit by hand.',
    '// Regenerate with: npm run seed:media',
    '//',
    '// Telegram file_id values are valid only for the bot that uploaded them.',
    '// If BOT_TOKEN changes, delete this file and re-run the seeder.',
    '',
  ].join('\n')

  const botId = shape.SEEDED_BOT_ID
    ? JSON.stringify(shape.SEEDED_BOT_ID)
    : 'null'

  const entries = Object.entries(shape.FILE_IDS).sort(([a], [b]) => a.localeCompare(b))
  const body =
    entries.length === 0
      ? '{}'
      : `{\n${entries.map(([name, id]) => `  ${JSON.stringify(name)}: ${JSON.stringify(id)},`).join('\n')}\n}`

  return `${header}\nexport const SEEDED_BOT_ID: string | null = ${botId}\n\nexport const FILE_IDS: Record<string, string> = ${body}\n`
}

async function persist(shape: SeedShape): Promise<void> {
  await fs.mkdir(OUTPUT_DIR, { recursive: true })
  await fs.writeFile(OUTPUT_FILE, serialize(shape), 'utf8')
}

function sleep(ms: number): Promise<void> {
  return new Promise((r) => setTimeout(r, ms))
}

interface TelegramErrorShape {
  code?: number
  description?: string
  response?: { parameters?: { retry_after?: number } }
  parameters?: { retry_after?: number }
}

function retryAfterFromError(err: unknown): number | undefined {
  const e = err as TelegramErrorShape
  return e?.response?.parameters?.retry_after ?? e?.parameters?.retry_after
}

async function main(): Promise<void> {
  if (!existsSync(IMAGES_DIR)) {
    console.error(`[seed] images directory not found: ${IMAGES_DIR}`)
    process.exit(1)
  }

  const bot = new Telegraf(BOT_TOKEN!)
  const me = await bot.telegram.getMe()
  const botId = String(me.id)
  console.log(`[seed] bot @${me.username} (id ${botId}) → chat ${CHAT_ID}`)

  const state = await loadExisting()
  if (state.SEEDED_BOT_ID && state.SEEDED_BOT_ID !== botId) {
    console.error(
      `[seed] refusing to write: existing generated map was seeded by bot ` +
        `${state.SEEDED_BOT_ID}, but BOT_TOKEN belongs to ${botId}.\n` +
        `       file_ids are bot-scoped — delete ${path.relative(process.cwd(), OUTPUT_FILE)} or pass --force.`,
    )
    process.exit(1)
  }
  state.SEEDED_BOT_ID = botId

  const entries = (await fs.readdir(IMAGES_DIR))
    .filter((f) => IMAGE_EXTENSIONS.has(path.extname(f).toLowerCase()))
    .sort()

  if (entries.length === 0) {
    console.log('[seed] no images found, nothing to do.')
    return
  }

  let uploaded = 0
  let skipped = 0

  for (const filename of entries) {
    if (state.FILE_IDS[filename]) {
      skipped++
      continue
    }

    const filePath = path.join(IMAGES_DIR, filename)
    let attempt = 0
    // Cap retries so a permanent failure doesn't loop forever; Telegram's
    // retry_after is usually <60s so 5 tries covers normal rate-limit waves.
    const MAX_ATTEMPTS = 5

    while (true) {
      attempt++
      try {
        const msg = await bot.telegram.sendPhoto(
          CHAT_ID!,
          { source: filePath },
          { caption: `seed: ${filename}`, disable_notification: true },
        )
        const largest = pickLargest(msg.photo ?? [])
        if (!largest?.file_id) {
          throw new Error(`telegram returned no photo sizes for ${filename}`)
        }
        state.FILE_IDS[filename] = largest.file_id
        await persist(state)
        uploaded++
        console.log(`[seed] uploaded ${filename} → ${largest.file_id.slice(0, 16)}…`)
        break
      } catch (err) {
        const retryAfter = retryAfterFromError(err)
        if (retryAfter && attempt < MAX_ATTEMPTS) {
          console.warn(
            `[seed] rate limited on ${filename}, sleeping ${retryAfter}s ` +
              `(attempt ${attempt}/${MAX_ATTEMPTS})`,
          )
          await sleep((retryAfter + 1) * 1000)
          continue
        }
        console.error(`[seed] failed for ${filename}:`, err)
        throw err
      }
    }

    // Gentle pacing between uploads — Telegram allows ~30 messages/sec to
    // different chats but only ~1 msg/sec to the same chat. We're hammering
    // one chat, so stay well under the limit.
    await sleep(1100)
  }

  console.log(
    `[seed] done. uploaded=${uploaded} skipped=${skipped} total=${entries.length}`,
  )
}

main().catch((err) => {
  console.error('[seed] fatal:', err)
  process.exit(1)
})
